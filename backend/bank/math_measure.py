@template("m.meas.shaded", "hard")
def _shaded_square_circle():
    use_pi_dec = random.random() < 0.45
    mode = random.choice(["inscribed", "four_quarters"])
    if use_pi_dec:
        r = random.choice([5, 6, 8, 10, 12, 15, 20, 25])
        side = 2 * r
        sq_area = side * side
        circ_area = 3.14 * r * r
        pi_lbl = "3.14"
        circum = 2 * 3.14 * r
    else:
        k = random.randint(1, 8)
        r = 7 * k
        side = 2 * r
        sq_area = side * side
        circ_area = 154 * k * k
        pi_lbl = "[[22/7]]"
        circum = 44 * k
    shaded = sq_area - circ_area
    s = 110
    x0, y0 = 55, 18
    if mode == "inscribed":
        fig = svg.canvas(220, 155, [
            svg.rect(x0, y0, s, s, shade=True),
            svg.circle((x0 + s / 2, y0 + s / 2), s / 2, shade=False),
            svg.label((x0 + s / 2, y0 + s + 16), f"{side} ซม.", size=12, cls="fig-dim"),
        ])
        desc = "วงกลมแนบในรูปสี่เหลี่ยมจัตุรัส"
