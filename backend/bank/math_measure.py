@template("m.meas.unit", "medium")
def _unit_thai_land_or_sq_meter():
    mode = random.choice(["land_to_sqm", "sqm_to_sqcm"])
    if mode == "land_to_sqm":
        rai = random.randint(1, 5)
        ngan = random.randint(1, 3)
        wa = random.choice([0, 20, 25, 40, 50, 75])
        total_sqwa = rai * 400 + ngan * 100 + wa
        total_sqm = total_sqwa * 4
        wa_txt = f" {wa} ตารางวา" if wa else ""
        return mcq(
            stem=f"ที่ดินแปลงหนึ่งมีเนื้อที่ {rai} ไร่ {ngan} งาน{wa_txt} คิดเป็นเนื้อที่กี่ตารางเมตร",
            correct=f"{num(total_sqm)} ตร.ม.",
            wrongs=[
                W(f"{num(total_sqwa)} ตร.ม.", "แปลงเป็นตารางวาแล้วลืมคูณ 4 เพื่อเปลี่ยนเป็นตารางเมตร", "partial"),
                W(f"{num(total_sqwa * 2)} ตร.ม.", "คูณด้วย 2 เพราะคิดว่า 1 ตารางวา = 2 ตารางเมตร (จริง ๆ ต้องเป็น 2×2 = 4 ตร.ม.)", "unit"),
                W(f"{num((rai * 100 + ngan * 10 + wa) * 4)} ตร.ม.", "จำหน่วยที่ดินผิดว่า 1 ไร่ = 100 ตารางวา", "unit"),
            ],
            hint="1 ไร่ = 400 ตารางวา, 1 งาน = 100 ตารางวา และ 1 ตารางวา = 4 ตารางเมตร",
            steps=[
                f"แปลงเป็นตารางวา: ({rai} × 400) + ({ngan} × 100) + {wa} = {num(total_sqwa)} ตารางวา",
                f"เนื่องจาก 1 ตารางวา = 4 ตารางเมตร",
                f"ดังนั้นมีเนื้อที่ = {num(total_sqwa)} × 4 = {num(total_sqm)} ตร.ม.",
            ],
        )
    sqm = random.choice([1.2, 1.5, 2.4, 2.5, 3.2, 3.6, 4.5, 0.8, 0.75])
    tile_side = random.choice([20, 25, 40, 50])
    total_sqcm = int(round(sqm * 10000))
    tile_area = tile_side * tile_side
    if total_sqcm % tile_area != 0:
        return None
    tiles = total_sqcm // tile_area
    return mcq(
        stem=f"ผนังห้องมีพื้นที่ {dec(sqm)} ตารางเมตร ต้องการปูกระเบื้องรูปสี่เหลี่ยมจัตุรัสยาวด้านละ {tile_side} เซนติเมตร จะต้องใช้กระเบื้องอย่างน้อยกี่แผ่น",
        correct=f"{num(tiles)} แผ่น",
        wrongs=[
            W(f"{dec(sqm * 100 / tile_area, 1) if sqm * 100 >= tile_area else max(1, tiles // 10)} แผ่น",
              "แปลง 1 ตร.ม. = 100 ตร.ซม. หรือ 1,000 ตร.ซม. แทนที่จะเป็น 10,000 ตร.ซม.", "unit"),
            W(f"{num(total_sqcm // tile_side)} แผ่น", f"หารด้วยความยาวด้าน {tile_side} ซม. เพียงครั้งเดียว ลืมหาพื้นที่กระเบื้อง ({tile_side}×{tile_side})", "formula"),
            W(f"{num(tiles * 2)} แผ่น", "คำนวณการหารพื้นที่ผิดพลาด", "calc"),
        ],
        hint="1 ตารางเมตร = 100 ซม. × 100 ซม. = 10,000 ตารางเซนติเมตร",
        steps=[
            f"พื้นที่ผนัง = {dec(sqm)} × 10,000 = {num(total_sqcm)} ตร.ซม.",
            f"พื้นที่กระเบื้อง 1 แผ่น = {tile_side} × {tile_side} = {num(tile_area)} ตร.ซม.",
            f"จำนวนกระเบื้องที่ใช้ = {num(total_sqcm)} ÷ {num(tile_area)} = {num(tiles)} แผ่น",
        ],
    )


