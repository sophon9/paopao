            W(f"{dec(circ_area, 2)} ตร.ซม.", "ตอบพื้นที่ของวงกลม แทนที่จะนำไปลบออกจากพื้นที่สี่เหลี่ยมจัตุรัส", "partial"),
            W(f"{dec(sq_area - circ_area / 4, 2)} ตร.ซม.", "หักพื้นที่ออกเพียง 1 มุม ([[1/4]] ของวงกลม) แทนที่จะหักครบทั้งวง", "partial"),
            W(f"{dec(sq_area - circum, 2)} ตร.ซม.", "เผลอนำความยาวรอบวงไปลบออกจากพื้นที่สี่เหลี่ยมจัตุรัส", "formula"),
