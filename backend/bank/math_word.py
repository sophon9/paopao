@template("m.word.time_cal", "hard")
def _clock_hands_angle():
    h = random.randint(1, 11)
    m = random.choice([10, 15, 20, 24, 30, 36, 40, 45, 50])
    ha = (h % 12) * 30 + m * 0.5
    ma = m * 6
    diff = abs(ha - ma)
    if diff > 180:
        diff = 360 - diff
    # Stationary hour hand trap (forgetting 0.5 * m)
    trap_stat = abs((h % 12) * 30 - ma)
    if trap_stat > 180:
        trap_stat = 360 - trap_stat
    if diff == trap_stat or diff == 0:
        return None
    fig = svg.clock(h, m, size=145)
    ans_str = dec(diff, 1)
    trap_str = dec(trap_stat, 1)
    return mcq(
        stem=f"จากรูปหน้าปัดนาฬิกาแสดงเวลา {h:02d}:{m:02d} น. เข็มสั้นและเข็มยาวทำมุมกันกี่องศา (ตอบมุมที่มีขนาดไม่เกิน 180°)",
        figure=fig,
        correct=f"{ans_str}°",
        wrongs=[
            W(f"{trap_str}°",
              f"คิดว่าเข็มสั้นหยุดนิ่งอยู่ที่เลข {h} พอดี ลืมคิดมุมที่เข็มสั้นเดินเพิ่มนาทีละ 0.5° ({dec(m * 0.5, 1)}°)", "trap"),
            W(f"{dec(abs(diff - m), 1)}°", "คิดว่าเข็มสั้นเดินนาทีละ 1° แทนที่จะเป็นนาทีละ 0.5°", "formula"),
            W(f"{dec(360 - diff, 1)}°", "ตอบมุมกลับ (มากกว่า 180°) แทนที่จะตอบมุมเล็ก", "misread"),
        ],
        hint="เข็มยาวเดินนาทีละ 6° ส่วนเข็มสั้นเดินชั่วโมงละ 30° และเดินเพิ่มอีกนาทีละ 0.5°",
        steps=[
            f"วัดมุมจากเลข 12 ตามเข็มนาฬิกา: เข็มยาวชี้ที่ {m} นาที = {m} × 6° = {ma}°",
            f"เข็มสั้นอยู่ที่ ({h} × 30°) + ({m} × 0.5°) = {h * 30}° + {dec(m * 0.5, 1)}° = {dec(ha, 1)}°",
            f"ขนาดของมุมระหว่างเข็มทั้งสอง = |{dec(ha, 1)}° − {ma}°| = {ans_str}°",
        ],
    )


