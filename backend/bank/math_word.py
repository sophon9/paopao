            f"ท่อน้ำเข้าไหลได้{t_unit}ละ {lcm_v} ÷ {t_in} = {r_in} หน่วย และท่อระบายออกไหลออก{t_unit}ละ {lcm_v} ÷ {t_out} = {r_out} หน่วย",
