@template("m.word.speed", "easy")
def _speed_basic_time_unit():
    v = random.choice([40, 50, 60, 72, 80, 90, 100, 120])
    mins = random.choice([15, 20, 30, 45, 75, 90, 120, 150])
    if (v * mins) % 60 != 0:
        v = 60
    dist = v * mins // 60
    person = name_th()
    hrs = mins // 60
    rem_m = mins % 60
    time_txt = f"{hrs} ชั่วโมง {rem_m} นาที" if hrs and rem_m else (f"{hrs} ชั่วโมง" if hrs else f"{mins} นาที")
    trap_dec = int(round(v * (hrs + rem_m / 100))) if rem_m else v * hrs + 20
    return mcq(
        stem=f"{person}ขับรถด้วยอัตราเร็วคงที่ {v} กิโลเมตรต่อชั่วโมง เป็นเวลา {time_txt} จะได้ระยะทางกี่กิโลเมตร",
        correct=f"{num(dist)} กม.",
        wrongs=[
            W(f"{num(trap_dec)} กม.", f"แปลง {rem_m} นาที เป็น .{rem_m} ชั่วโมงโดยตรง แทนที่จะหารด้วย 60 นาที", "unit"),
            W(f"{num(v * mins)} กม.", "นำอัตราเร็ว (กม./ชม.) คูณจำนวนนาทีโดยลืมหารด้วย 60", "unit"),
            W(f"{num(dist + v // 2)} กม.", "คำนวณสัดส่วนเวลาเป็นชั่วโมงผิดพลาด", "calc"),
        ],
        hint="เปลี่ยนเวลาเป็นชั่วโมงก่อน (นาที ÷ 60) แล้วคูณด้วยอัตราเร็ว (กม./ชม.)",
        steps=[
            f"เวลา {time_txt} = {mins} นาที = [[{mins}/60]] ชั่วโมง",
            f"ระยะทาง = อัตราเร็ว × เวลา = {v} × [[{mins}/60]] = {num(dist)} กม.",
        ],
    )


@template("m.word.speed", "medium")
def _speed_meet_or_catchup():
    mode = random.choice(["meet", "catchup"])
    p1, p2 = name_th(2)
    if mode == "meet":
        v1 = random.choice([45, 50, 55, 60, 65, 70])
        v2 = random.choice([55, 60, 70, 75, 80, 85])
        if v1 == v2:
            v2 += 10
        t = random.choice([2, 3, 4, 5])
        dist = (v1 + v2) * t
        return mcq(
            stem=f"บ้านของ{p1}และ{p2}อยู่ห่างกัน {num(dist)} กิโลเมตร ทั้งสองคนขับรถออกจากบ้านของตนเองพร้อมกันและแล่นสวนทางกัน โดย{p1}ขับด้วยอัตราเร็ว {v1} กม./ชม. และ{p2}ขับด้วยอัตราเร็ว {v2} กม./ชม. อีกกี่ชั่วโมงทั้งสองคนจึงจะพบกัน",
            correct=f"{t} ชั่วโมง",
            wrongs=[
                W(f"{dec(dist / abs(v2 - v1), 1)} ชั่วโมง", "นำอัตราเร็วมาลบกันแทนที่จะบวกกัน (แล่นสวนทางเข้าหากันต้องนำอัตราเร็วมาบวกกัน)", "concept"),
                W(f"{dec(dist / v1, 1)} ชั่วโมง", f"หารด้วยอัตราเร็วของ{p1}เพียงคนเดียว", "partial"),
                W(f"{t + 1} ชั่วโมง", "บวกอัตราเร็วหรือหารเลขผิดพลาด", "calc"),
            ],
            hint="เมื่อแล่นเข้าหากัน ระยะห่างจะลดลงชั่วโมงละ (อัตราเร็วคันที่ 1 + อัตราเร็วคันที่ 2)",
            steps=[
                f"แล่นสวนทางเข้าหากัน อัตราเร็วรวม = {v1} + {v2} = {v1 + v2} กม./ชม.",
                f"เวลาที่ใช้จนพบกัน = ระยะห่าง ÷ อัตราเร็วรวม = {num(dist)} ÷ {v1 + v2} = {t} ชั่วโมง",
            ],
        )
    # Catch-up problem: p1 starts head_t hours earlier at speed v1, then p2 chases at speed v2
    v1 = random.choice([40, 45, 50, 60])
    diff_v = random.choice([15, 20, 25, 30])
    v2 = v1 + diff_v
    chase_t = random.choice([2, 3, 4])
    head_dist = diff_v * chase_t
    return mcq(
        stem=f"{p1}ขับรถออกจากจุดเริ่มต้นด้วยอัตราเร็ว {v1} กม./ชม. จนอยู่ห่างจากจุดเริ่มต้น {head_dist} กิโลเมตร {p2}จึงเริ่มขับรถออกจากจุดเดียวกันไล่ตามไปในเส้นทางเดิมด้วยอัตราเร็ว {v2} กม./ชม. {p2}ต้องใช้เวลากี่ชั่วโมงจึงจะไล่ทัน{p1}",
        correct=f"{chase_t} ชั่วโมง",
        wrongs=[
            W(f"{dec(head_dist / (v1 + v2), 2)} ชั่วโมง", "นำอัตราเร็วมาบวกกันเหมือนการแล่นสวนทาง ทั้งที่เป็นการแล่นไล่ตามกัน", "concept"),
            W(f"{dec(head_dist / v2, 2)} ชั่วโมง", f"คิดว่า{p1}หยุดนิ่งอยู่กับที่ จึงหารด้วยอัตราเร็วของ{p2}เพียงอย่างเดียว", "trap"),
            W(f"{chase_t + 1} ชั่วโมง", "คำนวณผลต่างอัตราเร็วผิดพลาด", "calc"),
        ],
        hint="การไล่ตามกัน ระยะห่างจะลดลงชั่วโมงละ (อัตราเร็วผู้ไล่ − อัตราเร็วผู้ถูกไล่)",
        steps=[
            f"ในแต่ละชั่วโมง {p2}จะเข้าใกล้{p1}ได้ = {v2} − {v1} = {diff_v} กม.",
            f"เดิมห่างกัน {head_dist} กม. ดังนั้นใช้เวลาไล่ทัน = {head_dist} ÷ {diff_v} = {chase_t} ชั่วโมง",
        ],
    )


@template("m.word.speed", "challenge")
def _average_speed_or_train_bridge():
    mode = random.choice(["avg_speed_trap", "train_bridge"])
    if mode == "avg_speed_trap":
        pairs = [
            (30, 60), (40, 60), (20, 30), (30, 70), (40, 120), (60, 90), (50, 75), (12, 24), (15, 30)
        ]
        v1, v2 = pick(pairs)
        v_avg = (2 * v1 * v2) / (v1 + v2)
        v_avg_str = dec(v_avg, 1)
        trap_arith = dec((v1 + v2) / 2, 1)
        person = name_th()
        return mcq(
            stem=f"{person}ขับรถจากบ้านไปต่างจังหวัดด้วยอัตราเร็วคงที่ {v1} กม./ชม. และขากลับใช้เส้นทางเดิมด้วยอัตราเร็วคงที่ {v2} กม./ชม. อัตราเร็วเฉลี่ยของการเดินทางทั้งไปและกลับเป็นกี่กิโลเมตรต่อชั่วโมง",
            correct=f"{v_avg_str} กม./ชม.",
            wrongs=[
                W(f"{trap_arith} กม./ชม.",
                  f"นำ ({v1} + {v2}) ÷ 2 โดยตรง ซึ่งเป็นกับดักยอดฮิต! (เพราะขาไปและขากลับใช้เวลาไม่เท่ากัน)", "trap"),
                W(f"{dec(v_avg / 2, 1)} กม./ชม.", "ใช้ระยะทางเที่ยวเดียวแทนที่จะใช้ระยะทางรวมไป-กลับ (2 เท่า)", "partial"),
                W(f"{v1 + v2} กม./ชม.", "นำอัตราเร็วทั้งสองมาบวกกัน", "concept"),
            ],
            hint="อัตราเร็วเฉลี่ย = ระยะทางรวมไป-กลับ ÷ เวลารวมไป-กลับ (สมมติระยะทางที่หารด้วยทั้งสองอัตราเร็วลงตัว)",
            steps=[
                f"สมมติระยะทางเที่ยวเดียว = {v1 * v2 // math.gcd(v1, v2)} กม. (ค.ร.น. ของ {v1} และ {v2})",
                f"เวลาขาไป = {v1 * v2 // math.gcd(v1, v2)} ÷ {v1} = {v2 // math.gcd(v1, v2)} ชม. และขากลับ = {v1 // math.gcd(v1, v2)} ชม.",
                f"ระยะทางรวมไป-กลับ = 2 × {v1 * v2 // math.gcd(v1, v2)} = {2 * v1 * v2 // math.gcd(v1, v2)} กม. ใช้เวลารวม {(v1 + v2) // math.gcd(v1, v2)} ชม.",
                f"อัตราเร็วเฉลี่ย = {2 * v1 * v2 // math.gcd(v1, v2)} ÷ {(v1 + v2) // math.gcd(v1, v2)} = {v_avg_str} กม./ชม.",
            ],
        )
    # Train passing a bridge/tunnel: speed in m/s or km/h
    v_ms = random.choice([15, 20, 25, 30])
    v_kmh = v_ms * 18 // 5
    train_len = random.choice([120, 150, 180, 200, 240, 250])
    bridge_len = random.choice([300, 350, 400, 450, 500, 600])
    total_d = train_len + bridge_len
    if total_d % v_ms != 0:
        bridge_len = ((total_d // v_ms) + 1) * v_ms - train_len
        total_d = train_len + bridge_len
    sec = total_d // v_ms
    trap_only_bridge = dec(bridge_len / v_ms, 1)
    return mcq(
        stem=f"รถไฟขบวนหนึ่งยาว {train_len} เมตร แล่นด้วยอัตราเร็ว {v_kmh} กิโลเมตรต่อชั่วโมง จะใช้เวลากี่วินาทีในการแล่นผ่านสะพานที่ยาว {bridge_len} เมตร จนพ้นสะพานทั้งขบวน",
        correct=f"{sec} วินาที",
        wrongs=[
            W(f"{trap_only_bridge} วินาที", "ใช้เฉพาะความยาวสะพาน ลืมบวกความยาวขบวนรถไฟเพื่อให้ท้ายขบวนพ้นสะพาน", "trap"),
            W(f"{dec(total_d / v_kmh, 1)} วินาที", f"หารด้วยอัตราเร็ว {v_kmh} กม./ชม. โดยตรง ลืมแปลงเป็นเมตรต่อวินาที ({v_ms} ม./วินาที)", "unit"),
            W(f"{dec(train_len / v_ms, 1)} วินาที", "คิดเฉพาะความยาวรถไฟ ลืมบวกความยาวสะพาน", "partial"),
        ],
        hint="1) แปลงอัตราเร็ว กม./ชม. เป็น ม./วินาที โดยคูณ [[5/18]]  2) ระยะทางที่หัวรถไฟต้องเคลื่อนที่จนท้ายขบวนพ้นสะพาน = ความยาวสะพาน + ความยาวรถไฟ",
        steps=[
            f"แปลงอัตราเร็ว: {v_kmh} กม./ชม. = {v_kmh} × [[5/18]] = {v_ms} เมตร/วินาที",
            f"ระยะทางทั้งหมดจนท้ายขบวนพ้นสะพาน = {bridge_len} + {train_len} = {total_d} เมตร",
            f"เวลาที่ใช้ = {total_d} ÷ {v_ms} = {sec} วินาที",
        ],
    )


