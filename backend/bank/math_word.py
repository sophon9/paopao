@template("m.word.work", "challenge")
def _pipe_inlet_outlet():
    pairs = [
        (3, 6), (4, 6), (4, 12), (5, 10), (6, 8), (6, 9), (6, 12), (6, 18),
        (8, 12), (8, 24), (9, 18), (10, 15), (10, 20), (12, 15), (12, 18),
        (12, 20), (12, 24), (15, 20), (15, 30), (18, 36), (20, 30),
    ]
    t_in, t_out = pick(pairs)
    container = random.choice(["ถังน้ำ", "สระน้ำ", "อ่างเก็บน้ำ", "แท็งก์น้ำ"])
    t_unit = random.choice(["ชั่วโมง", "นาที"])
    lcm_v = (t_in * t_out) // math.gcd(t_in, t_out)
    r_in = lcm_v // t_in
    r_out = lcm_v // t_out
    net_r = r_in - r_out
    hrs = Fraction(lcm_v, net_r)
    ans_str = dec(float(hrs), 1) if hrs.denominator in (1, 2, 5) else frac(hrs, mixed=True)
    trap_add = Fraction(lcm_v, r_in + r_out)
